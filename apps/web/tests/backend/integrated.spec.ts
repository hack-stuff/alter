import { expect, test } from '@playwright/test'
import { openScreen, showMoreRequests, workLogEntry } from '../nav'

test('persistent backend: cited A2A, reviewed Google simulation, welcome reply, invite and reset',async({page,browser,isMobile})=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Your name').fill('Alex')
  await page.getByRole('button',{ name: 'Continue' }).click()
  await expect(page.getByRole('heading',{name:"Alex's Alter"})).toBeVisible()
  await expect(page.getByTitle('Local development · simulated AI', {exact:false})).toBeVisible()
  await expect(page.getByRole('status').filter({hasText:'Setting up your team'})).toHaveCount(0)
  const nav = (name: string) => openScreen(page, name)
  await nav('Home')
  await showMoreRequests(page); await page.getByRole('button',{name:'Add a QA update to the status doc'}).click()
  await page.getByRole('button',{name:'Review proposal'}).click()
  const card=page.getByRole('article',{name:'Login revamp · QA update'}).filter({visible:true})
  await expect(card).toBeVisible()
  // Doc changes apply directly and stay listed as a record; only emails wait for approval.
  await expect(card.getByRole('status')).toHaveText('Applied')
  const fileUrl=await card.getByRole('link',{name:'Open updated file'}).getAttribute('href')
  expect(fileUrl).toContain('/local/files/')
  const resource=await page.request.get(fileUrl!)
  expect(await resource.text()).toContain('one-tap sign-in backend')
  await nav('Team')
  await page.getByRole('button',{name:"Ask Siddhi's Alter"}).click()
  await page.getByLabel("Question for Siddhi's Alter").fill('Why one-tap?')
  await page.getByRole('button',{name:'Send question'}).click()
  await expect(page.getByText('✓ Allowed',{exact:true})).toBeVisible()
  await expect(page.getByRole('region',{name:'Answer'}).getByLabel('Sources', {exact:true}).first()).toBeVisible()
  await page.getByLabel("Question for Siddhi's Alter").fill('Confirm Nov 3')
  await page.getByRole('button',{name:'Send question'}).click()
  await expect(page.getByText('⚑ Asked Siddhi',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Copy invite link'}).click()
  const invite=await page.getByLabel('Invite link').inputValue().catch(async()=>{
    // Clipboard succeeds on Chromium; retrieve the same server-created invite from the scoped API.
    return page.evaluate(async()=>{
      const uid=localStorage.getItem('alter.dev.uid')!
      const response=await fetch('http://127.0.0.1:8082/v1/workspace',{headers:{'X-Dev-Uid':uid}})
      return location.origin+'/join/'+(await response.json()).workspace.inviteCode
    })
  })
  const guestContext=await browser.newContext(isMobile?{viewport:{width:393,height:851}}:{})
  const guest=await guestContext.newPage()
  await guest.goto(invite)
  await guest.getByLabel('Your name').fill('Jamie')
  await guest.getByRole('button',{ name: 'Continue' }).click()
  await expect(guest.getByRole('heading',{name:"Jamie's Alter"})).toBeVisible()
  await nav('Decisions')
  const question=page.getByRole('article').filter({hasText:'Can QA commit'})
  await expect(question).toBeVisible()
  await question.getByLabel('Your reply').fill('I need another test run before choosing a date.')
  await question.getByRole('button',{name:'Review reply'}).click()
  await question.getByRole('button',{name:'Send reply'}).click()
  await expect(question.getByText('Your answer:',{exact:false})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:"Alex's Alter"})).toBeVisible()
  // The applied doc change never waits in Approvals; after a reload the Work log still records it.
  await nav('Approvals')
  await expect(page.getByRole('article',{name:'Login revamp · QA update'}).filter({visible:true})).toHaveCount(0)
  await nav('Work log')
  await expect(workLogEntry(page,'Applied Login revamp · QA update')).toContainText('doc edit')
  await nav('Rules')
  await page.getByRole('button',{name:'Reset Alter'}).click()
  await page.getByRole('button',{name:'Confirm reset'}).click()
  await expect(page.getByRole('heading',{name:"Alex's Alter"})).toBeVisible()
  await showMoreRequests(page)
  await expect(page.getByRole('button',{name:'Add a QA update to the status doc'})).toBeVisible()
  await guest.reload()
  await expect(guest.getByRole('heading',{name:"Jamie's Alter"})).toBeVisible()
  await guestContext.close()
  expect(errors).toEqual([])
})
