import { test, expect } from '@playwright/test'

test('meeting review: transcript, mobile cards, edit, approved work and background follow-up', async ({ page }, info) => {
  const errors: string[] = []
  await page.setExtraHTTPHeaders({ 'X-Real-IP': info.project.name === 'mobile' ? '127.0.0.3' : '127.0.0.2' })
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('Your name').fill('Priya demo')
  await page.getByRole('button', { name: 'Get my Alter' }).click()
  await expect(page.getByRole('heading', { name: "Priya demo's Alter" })).toBeVisible()
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name: 'work', exact: true }).click()
  await page.getByRole('button', { name: 'New meeting' }).click()
  await page.getByLabel('The participants consent', { exact: false }).check()
  await page.getByRole('button', { name: 'Start capture', exact: true }).click()
  const transcript = "Rahul switched to Google one-tap on October 8.\nWhen are we launching this?\nMeera, update the mock-ups.\nPriya will update the status doc."
  await page.getByLabel('Add meeting transcript').fill(transcript)
  await page.getByRole('button', { name: 'Save transcript', exact: true }).click()
  await expect(page.getByText('4 saved segments', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Prepare my review' }).click()
  await expect(page.getByRole('tab', { name: 'Status doc' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Login revamp — status' })).toBeVisible()
  await page.getByLabel('One more thing to change?').fill("Add that Meera's mock-ups are due Friday.")
  await page.getByRole('button', { name: 'Apply edit', exact: true }).click()
  await page.getByRole('tab', { name: 'Task board' }).click()
  await expect(page.getByText('Meera · Friday', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Status doc' }).click()
  await expect.poll(() => page.locator('.review-strip').evaluate((element) => Math.round(element.scrollLeft))).toBe(0)
  await page.screenshot({ path: info.outputPath('meeting-review.png'), fullPage: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: info.outputPath('meeting-viewport.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel('Let my Alter resolve the production-readiness follow-up.', { exact: false }).check()
  await page.getByRole('button', { name: 'Review and approve', exact: true }).click()
  // Another view changes the bundle after confirmation was opened. Require review again.
  await page.evaluate(async () => {
    const modulePath = '/src/api/meetings.ts'
    const { meetingApi } = await import(modulePath)
    const id = sessionStorage.getItem('alter.open.meeting')!
    const current = await meetingApi.get(id)
    await meetingApi.revise(id, current.revision, 'Keep the launch date awaiting Rahul.')
  })
  await expect(page.getByRole('button', { name: 'Approve reviewed changes' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Review and approve', exact: true }).click()
  await page.getByRole('button', { name: 'Approve reviewed changes' }).click()
  await expect(page.getByText('2 reviewed actions completed.', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'One less thing to chase.' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open updated document' })).toHaveAttribute('href', /\/local\/files\//)
  await page.getByRole('button', { name: 'Refresh current document' }).click()
  await expect(page.getByText('Production readiness', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name: 'work', exact: true }).click()
  await expect(page.getByText('2 reviewed actions completed.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
