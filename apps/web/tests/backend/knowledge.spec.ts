import { expect, test } from '@playwright/test'
import { openScreen } from '../nav'

test('source and memory controls preserve review and audience through corrections', async ({ page }, info) => {
  await page.setExtraHTTPHeaders({ 'X-Real-IP': info.project.name === 'mobile' ? '127.0.0.7' : '127.0.0.6' })
  await page.goto('/')
  await page.getByLabel('Your name').fill('Knowledge demo')
  await page.getByRole('button', { name: 'Get my Alter' }).click()
  await openScreen(page, 'Rules')
  await page.getByLabel('Teach your Alter something').fill('Lighthouse uses the blue checklist.')
  await expect(page.getByLabel('Use new guidance')).toHaveValue('owner')
  await page.getByRole('button', { name: 'Teach', exact: true }).click()
  let memory = page.locator('article.memory').filter({ hasText: 'Lighthouse uses the blue checklist.' })
  await expect(memory).toContainText('Only for your own work')
  await memory.getByRole('button', { name: 'Approve memory' }).click()
  await memory.getByRole('button', { name: 'Edit guidance' }).click()
  await memory.getByLabel('Corrected guidance').fill('Lighthouse uses the green checklist.')
  await memory.getByRole('button', { name: 'Save for review' }).click()
  memory = page.locator('article.memory').filter({ hasText: 'Lighthouse uses the green checklist.' })
  await expect(memory).toContainText('proposed')
  await expect(memory).toContainText('v2')
  await memory.getByRole('button', { name: 'Approve memory' }).click()
  await page.getByLabel('Source title').fill('Selected project notes')
  await page.getByLabel('Selected source excerpt').fill('Lighthouse batches accessibility checks before release.')
  await page.getByRole('button', { name: 'Import excerpt' }).click()
  const source = page.locator('article.memory').filter({ hasText: 'Selected project notes' })
  await expect(source).toContainText('owner')
  await source.getByRole('button', { name: 'Update excerpt' }).click()
  await source.getByLabel('Updated source excerpt').fill('Lighthouse batches accessibility and contrast checks.')
  await source.getByRole('button', { name: 'Save source revision' }).click()
  await expect(source).toContainText('v2')
  await source.getByRole('button', { name: 'Revoke source' }).click()
  await expect(source).toContainText('revoked')
})
